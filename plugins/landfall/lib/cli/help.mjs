// Help and reference rendering from the command table (spec §8.2, COD-5): `--help`, `<command> --help` and
// docs/cli.md (scripts/gen-docs.mjs) come from these functions only, so the three cannot disagree.
// ctx: { names (lib/name.json), commands, globalFlags, exitCodes }.
import { flagKey, mutates } from './commands.mjs';
import { ENVELOPE_VERSION, LIMITS, envelope, normalizeError } from './envelope.mjs';

const pad = (s, width) => s + ' '.repeat(Math.max(2, width - s.length));
const flagLabel = (f) => `${f.flag}${f.alias ? `, ${f.alias}` : ''}${f.value ? ` <${f.value}>` : ''}`;
const exitLine = (codes) => `Exit codes: ${codes.map((e) => `${e.code} ${e.name}`).join(' · ')}`;
const table = (rows) => {
  const width = Math.max(0, ...rows.map(([left]) => left.length)) + 2;
  return rows.map(([left, right]) => `  ${pad(left, width)}${right}`);
};

// Consent per form, read from the row's own mutates(): the bare form, and each flag whose form differs from it.
function forms(row) {
  const base = mutates(row);
  const flips = row.flags.filter((f) => mutates(row, { [flagKey(f.flag)]: f.value ? `<${f.value}>` : true }) !== base).map((f) => f.flag);
  return { base, flips, any: base || flips.length > 0 };
}
const CONSENT = 'needs a terminal or --yes, otherwise exit 7 REFUSED.';
function consentLine(row) {
  const { base, flips } = forms(row);
  if (base) return `Changes files: ${CONSENT}${flips.length ? ` Read-only with ${flips.join(', ')}: no consent needed.` : ''}`;
  return `Read-only.${flips.length ? ` Changes files with ${flips.join(', ')}: ${CONSENT}` : ''}`;
}

export function synopsis(row, bin) {
  const parts = [bin, row.name];
  for (const a of row.args) {
    const name = a.variadic ? `<${a.name}…>` : `<${a.name}>`;
    parts.push(a.required ? name : `[${name}]`);
  }
  for (const f of row.flags) parts.push(`[${f.flag}${f.value ? ` <${f.value}>` : ''}]`);
  if (forms(row).any) parts.push('[--yes]');
  if (!row.failOpen) parts.push('[--json]');
  return parts.join(' ');
}

// The usage lines: help, command help and usage errors all print these.
export const generalUsage = (bin) => `usage: ${bin} <command> [options]`;
export const groupUsage = (bin, group) => `usage: ${bin} ${group} <subcommand> [options]`;
export const commandUsage = (row, bin) => `usage: ${synopsis(row, bin)}`;

export function renderHelp({ names, commands, globalFlags, exitCodes }) {
  const visible = commands.filter((r) => !r.hidden);
  return [
    generalUsage(names.bin),
    '',
    'Commands:',
    ...(visible.length ? table(visible.map((r) => [r.name, r.summary])) : ['  (none)']),
    '',
    'Options:',
    ...table(globalFlags.map((f) => [flagLabel(f), f.summary])),
    '',
    exitLine(exitCodes),
    `Reference: docs/cli.md · ${names.bin} <command> --help`,
    '',
  ].join('\n');
}

export function renderCommandHelp(row, { names, exitCodes }) {
  const lines = [commandUsage(row, names.bin), '', row.summary, ...(row.details ?? [])];
  const args = row.args.filter((a) => a.summary);
  if (args.length) lines.push('', 'Arguments:', ...table(args.map((a) => [a.name, a.summary])));
  if (row.flags.length) lines.push('', 'Options:', ...table(row.flags.map((f) => [flagLabel(f), f.summary])));
  lines.push('');
  if (row.failOpen) lines.push('Internal: called by generated files; an error ends with exit 0 and no output, except a guard that cannot verify a guarded command (exit 2).');
  else lines.push(consentLine(row));
  lines.push(exitLine(exitCodes.filter((e) => row.exits.includes(e.name))), '');
  return lines.join('\n');
}

const fence = (text) => ['```text', text.replace(/\n$/, ''), '```'];

// One envelope line with placeholders, keys in the order envelope() emits them.
function envelopeExample() {
  const error = { code: '"<kebab>"', message: `"<≤ ${LIMITS.message} chars>"`, hint: `"<≤ ${LIMITS.hint} chars>"` };
  const errorItem = `{${Object.keys(normalizeError({})).map((k) => `"${k}":${error[k]}`).join(',')}}`;
  const value = { cli: String(ENVELOPE_VERSION), command: '"<name>"', ok: '<bool>', code: '<int>', exit: '"<NAME>"', data: '{…}', errors: `[${errorItem}]` };
  return `{${Object.keys(envelope({ command: '<name>', code: 0 })).map((k) => `"${k}":${value[k]}`).join(',')}}`;
}

export function renderDocs(ctx, { source }) {
  const { names, commands, exitCodes } = ctx;
  const bin = names.bin;
  const section = (row) => ['', `### \`${synopsis(row, bin)}\``, '', ...fence(renderCommandHelp(row, ctx))];
  const internal = commands.filter((r) => r.hidden);
  return [
    '# CLI reference',
    '',
    `<!-- Generated by scripts/gen-docs.mjs from ${source}; do not edit. Regenerate: node scripts/gen-docs.mjs -->`,
    '',
    `\`${bin}\` is on the Bash tool PATH while the plugin is enabled. Agents call it with \`--json\` and read the envelope; people read the text output.`,
    '',
    '## Envelope',
    '',
    'With `--json` every command prints exactly one line on stdout and nothing on stderr:',
    '',
    '```json',
    envelopeExample(),
    '```',
    '',
    '- `ok` is `true` exactly when `code` is 0; a non-zero code carries at least one error.',
    '- Partial data: `ok: false` with `data` holding what was computed and `data.partial: true`.',
    '- Without `--json`: text on stdout, errors with their hints on stderr.',
    '- Output carries no escape sequence, control, bidi or invisible character from data: text drops them and keeps the printable rest; the envelope writes them as `\\u` escapes, so `JSON.parse` gives the data back exactly.',
    '- A command that changes files refuses without a terminal unless `--yes` is given: exit 7 REFUSED (COD-9). Consent is per form: a command section names each flag whose form differs.',
    '- A command exits only with the codes its section lists, plus 2 USAGE (arguments) and 70 INTERNAL (bug); any other code is reported as 70.',
    '',
    '## Exit codes',
    '',
    '| Code | Name | Meaning |',
    '|---|---|---|',
    ...exitCodes.map((e) => `| ${e.code} | ${e.name} | ${e.meaning} |`),
    '',
    '## Usage',
    '',
    ...fence(renderHelp(ctx)),
    '',
    '## Commands',
    ...commands.filter((r) => !r.hidden).flatMap(section),
    ...(internal.length ? ['', '## Internal commands', '', 'Hidden from `--help`; generated files call them.', ...internal.flatMap(section)] : []),
    '',
  ].join('\n');
}
