// Command table (spec §8.1, §8.2, REV-54): the single source of commands, arguments, flags and exit codes.
// main.mjs parses argv by it; help.mjs renders `--help` from it and scripts/gen-docs.mjs renders docs/cli.md.
// A command is one row; `load` imports its implementation on demand, so hook calls start fast.
//
// Row: name (words separated by one space) · summary (≤ 120 chars) · details (extra help lines) ·
// args [{ name, required, variadic, summary }] · flags [{ flag, alias, value, summary }] · exits (EXIT names) ·
// mutating (changes files: needs a terminal or --yes, REV-58; for a command whose forms differ, a function of the
// parsed flags, true for a form that changes files: consent (main.mjs) and help (help.mjs) both read it through
// mutates()) · hidden (not in --help; docs list it as internal) ·
// failOpen (hook entry: an error ends with exit 0 and no output, GC8, except a block-if-guarded hook: exit 2) ·
// capability (a rollout capability of lib/config: while its flag is off the command is refused with REFUSED naming the
// flag, before consent and before it loads; spec §14 rollback; the row must list REFUSED) · load () => Promise<(ctx) => result>.
// A command returns { code?, data?, errors?: [{ code, message, hint }], text?, warnings?: [text], usage? } and never
// prints: lib/cli/output.mjs writes it (S2). code defaults to FAIL when errors are present, else OK.

export const EXIT_CODES = [
  { code: 0, name: 'OK', meaning: 'success; for `tick`: do the listed steps now (ACTION)' },
  { code: 1, name: 'FAIL', meaning: 'the command ran and the checked condition is false (verify failed, check found problems, claim held, merge conflict)' },
  { code: 2, name: 'USAGE', meaning: 'unknown command or flag, invalid value, limit exceeded' },
  { code: 3, name: 'WAIT', meaning: '`tick`: work in progress; `wait`: run still running; `heavy`: no slot within --wait' },
  { code: 4, name: 'DONE', meaning: '`tick`: loop complete' },
  { code: 5, name: 'STALLED', meaning: '`tick`: no progress within the stall window; `heavy`: no output within --idle' },
  { code: 6, name: 'BUDGET', meaning: '`tick`: a cap was reached; `heavy`: the --timeout was reached' },
  { code: 7, name: 'REFUSED', meaning: 'newer state schema, inactive repository for a write command, missing consent (no terminal and no `--yes`)' },
  { code: 8, name: 'ENV', meaning: 'environment problem: not a git repository, git, claude or a provider CLI missing, network for lanes' },
  { code: 70, name: 'INTERNAL', meaning: 'bug; the message asks for `doctor --json` output in an issue' },
];
export const EXIT = Object.fromEntries(EXIT_CODES.map((e) => [e.name, e.code]));

